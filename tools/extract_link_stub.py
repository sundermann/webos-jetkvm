"""Extract a retail ARM32 library's exports into a build-only linker script."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import struct
from dataclasses import dataclass
from pathlib import Path


@dataclass
class Library:
    soname: str
    symbols: dict[str, int]
    sha256: str


def read_library(path: Path) -> Library:
    data = path.read_bytes()
    if data[:7] != b"\x7fELF\x01\x01\x01":
        raise ValueError(f"{path}: expected a little-endian ELF32 library")
    header = struct.unpack_from("<16sHHIIIIIHHHHHH", data)
    if header[1:3] != (3, 40) or header[11] != 40 or not header[12]:
        raise ValueError(f"{path}: expected an ARM shared library with section headers")
    sections = [
        struct.unpack_from("<IIIIIIIIII", data, header[6] + index * header[11])
        for index in range(header[12])
    ]

    def section_bytes(index: int) -> bytes:
        section = sections[index]
        result = data[section[4] : section[4] + section[5]]
        if len(result) != section[5]:
            raise ValueError(f"{path}: truncated section")
        return result

    def string(table: bytes, offset: int) -> str:
        return table[offset : table.index(b"\0", offset)].decode("ascii")

    symbols = {}
    soname = ""
    versions = next((section_bytes(i) for i, s in enumerate(sections) if s[1] == 0x6FFFFFFF), None)
    for index, section in enumerate(sections):
        if section[1] not in (6, 11):  # SHT_DYNAMIC, SHT_DYNSYM
            continue
        strings = section_bytes(section[6])
        contents = section_bytes(index)
        if section[1] == 6:
            for offset in range(0, len(contents), 8):
                tag, value = struct.unpack_from("<II", contents, offset)
                if tag == 14:  # DT_SONAME
                    soname = string(strings, value)
            continue
        if section[9] != 16:
            raise ValueError(f"{path}: unsupported symbol entry size")
        for offset in range(0, len(contents), 16):
            name, _, _, info, other, section_index = struct.unpack_from("<IIIBBH", contents, offset)
            kind, binding, visibility = info & 15, info >> 4, other & 3
            if not section_index or binding not in (1, 2, 10) or visibility not in (0, 3):
                continue
            symbol_name = string(strings, name)
            if versions is not None:
                version = struct.unpack_from("<H", versions, offset // 8)[0] & 0x7FFF
                if version > 1:
                    raise ValueError(
                        f"{path}: versioned export {symbol_name} requires a version script"
                    )
            if kind not in (1, 2) or (binding == 10 and kind != 1):
                raise ValueError(f"{path}: unsupported exported symbol type for {symbol_name}")
            if not re.fullmatch(r"[A-Za-z_.$][A-Za-z_0-9.$]*", symbol_name):
                raise ValueError(f"{path}: unsupported linker symbol name {symbol_name!r}")
            if symbol_name in symbols:
                raise ValueError(f"{path}: duplicate export {symbol_name}")
            symbols[symbol_name] = kind
    if not soname or not symbols:
        raise ValueError(f"{path}: SONAME or exported symbols missing")
    return Library(soname, symbols, hashlib.sha256(data).hexdigest())


def export_source(library: Library) -> str:
    lines = [
        "/* Generated by tools/extract_link_stub.py; do not edit.",
        f" * Reference: {library.soname}, SHA-256 {library.sha256}",
        f" * Complete export list: {len(library.symbols)} symbols; no implementation code.",
        " * Build-only aliases to dummy.c. Never deploy the resulting library.",
        " */",
    ]
    for name, kind in sorted(library.symbols.items()):
        target = "dummy" if kind == 2 else "dummy_data"
        lines.append(f"{json.dumps(name)} = {json.dumps(target)};")
    # Keep the helper names out of the library's public export list.
    lines += ["", "VERSION { { local: dummy; dummy_data; }; }"]
    return "\n".join(lines) + "\n"


def verify(reference: Library, stub: Library) -> None:
    if reference.soname != stub.soname:
        raise ValueError(f"SONAME mismatch: {reference.soname} != {stub.soname}")
    missing = reference.symbols.keys() - stub.symbols.keys()
    extra = stub.symbols.keys() - reference.symbols.keys()
    mismatched = []
    for name in reference.symbols.keys() & stub.symbols.keys():
        if reference.symbols[name] != stub.symbols[name]:
            mismatched.append(name)
    if missing or extra or mismatched:
        raise ValueError(
            f"Export mismatch: missing={sorted(missing)}, extra={sorted(extra)}, "
            f"function/data type={sorted(mismatched)}"
        )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("library", type=Path, help="actual TV library, not a link stub")
    parser.add_argument("output", type=Path, nargs="?", help="generated native/stubs/*.lds file")
    parser.add_argument(
        "--check", action="store_true", help="check the generated file without changing it"
    )
    parser.add_argument(
        "--verify", type=Path, help="compare a built stub's entire export table with the reference"
    )
    args = parser.parse_args()
    if args.verify is None and args.output is None:
        parser.error("an output file or --verify is required")
    if args.check and args.output is None:
        parser.error("--check requires an output file")
    try:
        library = read_library(args.library)
        if args.verify is not None:
            verify(library, read_library(args.verify))
            print(f"Verified {library.soname}: all {len(library.symbols)} exports match")
        if args.output is not None:
            source = export_source(library)
            if args.check:
                if args.output.read_text() != source:
                    raise ValueError(f"{args.output}: does not match {args.library}")
            else:
                args.output.write_text(source)
            print(f"{library.soname}: {len(library.symbols)} exports -> {args.output}")
    except (OSError, ValueError, struct.error, IndexError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
